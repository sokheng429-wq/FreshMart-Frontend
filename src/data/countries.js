// regional-indicator flag emoji from an ISO-3166 alpha-2 code (e.g. KH → 🇰🇭)
export const flagOf = (code) =>
  String(code || '')
    .toUpperCase()
    .replace(/[^A-Z]/g, '')
    .split('')
    .map((ch) => String.fromCodePoint(127397 + ch.charCodeAt(0)))
    .join('')
